"""Markdown investigation report."""
from __future__ import annotations

from datetime import date


def _cell(text: object) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def build_report(analysis: dict, qa: list[dict] | None = None) -> str:
    repo = analysis["repo"]
    out: list[str] = [f"# Investigation Report: {repo['name']}", "", f"_Generated by The Last Maintainer on {date.today().isoformat()}._", ""]

    out += ["## Verified facts", "",
            "Extracted deterministically from source files; each item cites a file and line.", "",
            f"- Files scanned: {repo['file_count']}" + (" (limit reached)" if repo["truncated"] else ""),
            f"- Java sources: {repo['java_files']}",
            f"- Components: {len(analysis['components'])}, endpoints: {len(analysis['endpoints'])}, relationships: {len(analysis['relationships'])}",
            f"- Git repository: {'yes' if repo['is_git'] else 'no'}", ""]
    if repo["languages"]:
        out.append("Top file types: " + ", ".join(f"`{ext}` ({n})" for ext, n in repo["languages"].items()))
        out.append("")
    if repo["dependencies"]:
        out += ["### Dependencies", ""]
        out += [f"- `{d['name']}`" + (f" {d['version']}" if d["version"] else "") + f" ({d['source']})" for d in repo["dependencies"][:40]]
        out.append("")

    out += ["## API inventory", ""]
    if analysis["endpoints"]:
        out += ["| Method | Path | Handler | Source | Last commit |", "|---|---|---|---|---|"]
        for ep in analysis["endpoints"]:
            last = ep["history"][0] if ep["history"] else None
            last_text = f"`{last['short']}` {last['subject']}" if last else "n/a"
            out.append(
                f"| {ep['method']} | `{_cell(ep['path'])}` | {ep['controller']}.{ep['handler']} | `{ep['file']}:{ep['line']}` | {_cell(last_text)} |"
            )
    else:
        out.append("No endpoints detected.")
    out.append("")

    out += ["## Architecture", ""]
    if analysis["relationships"]:
        out += ["```mermaid", "graph LR"]
        for rel in analysis["relationships"]:
            out.append(f"  {rel['source']} -->|{rel['kind']}| {rel['target']}")
        out += ["```", "", "| From | Relationship | To | Evidence |", "|---|---|---|---|"]
        for rel in analysis["relationships"]:
            out.append(f"| {rel['source']} | {rel['kind']} | {rel['target']} | `{rel['file']}:{rel['line']}` |")
    else:
        out.append("No component relationships were established.")
    out.append("")

    out += ["## Git history", ""]
    if analysis["commits"]:
        out += [f"- `{c['short']}` {c['date'][:10]} {c['author']}: {c['subject']}" for c in analysis["commits"][:15]]
    else:
        out.append("No history available.")
    out.append("")

    gaps = analysis["doc_gaps"]
    out += ["## Documentation gaps", "",
            "_Heuristic matches (potential inconsistencies); verify before acting._", ""]
    if gaps["documented_not_found"]:
        out += ["**Documented but not found in source:**", ""]
        out += [f"- `{(g['method'] or 'ANY')} {g['path']}` in `{g['file']}:{g['line']}`: {g['problem']}" for g in gaps["documented_not_found"]]
        out.append("")
    if gaps["undocumented"]:
        out += ["**In source but not documented:**", ""]
        out += [f"- `{e['method']} {e['path']}` (`{e['file']}:{e['line']}`)" for e in gaps["undocumented"]]
        out.append("")
    if not gaps["documented_not_found"] and not gaps["undocumented"]:
        out += ["No inconsistencies detected.", ""]

    out += ["## Plausible explanations", ""]
    if qa:
        out += ["_AI-generated answers from a local model. Treat as plausible, not verified._", ""]
        for item in qa:
            out += [f"### {item.get('question', '')}", "", item.get("answer") or "(no answer)", ""]
            ids = ", ".join(f"{e['id']}: {e['title']}" for e in item.get("evidence", []))
            if ids:
                out += [f"Evidence: {ids}", ""]
    else:
        out += ["None recorded. Ask questions in the app and include them in the export.", ""]

    out += ["## Unanswered questions", ""]
    out += [f"- {q}" for q in analysis["open_questions"]] or ["- None identified automatically."]
    out.append("")
    return "\n".join(out)
